/// NavigationItem: কেন্দ্রীভূত নেভিগেশন আইটেম ডেটা মডেল
class NavigationItem {
  final String id;
  final String title;
  final String? englishTitle;
  final IconData icon;
  final String route;
  final List<NavigationItem> children;
  final String? permissionKey;
  final List<String>? requiredAnyPermissions;
  final List<String>? requiredAllPermissions;
  final bool isVisible;
  final int sortOrder;
  final String? badgeText;
  final String? description;
  final bool isStandalone;

  const NavigationItem({
    required this.id,
    required this.title,
    this.englishTitle,
    required this.icon,
    required this.route,
    this.children = const [],
    this.permissionKey,
    this.requiredAnyPermissions,
    this.requiredAllPermissions,
    this.isVisible = true,
    required this.sortOrder,
    this.badgeText,
    this.description,
    this.isStandalone = false,
  });

  bool get hasChildren => children.isNotEmpty;
}

/// BreadcrumbItem: ব্রেডক্রাম্ব প্রদর্শনের জন্য সহায়ক মডেল
class BreadcrumbItem {
  final String title;
  final String route;
  final bool isCurrent;

  const BreadcrumbItem({
    required this.title,
    required this.route,
    this.isCurrent = false,
  });
}

