  /// রুট স্ট্রিং দিয়ে মেইন প্যারেন্ট মডিউল খুঁজে বের করা
  static NavigationItem? findParentModuleByRoute(String route) {
    for (final module in mainModules) {
      if (module.route == route) return module;
      for (final child in module.children) {
        if (child.route == route) return module;
      }
    }
    return null;
  }

  /// রুট স্ট্রিং দিয়ে নির্দিষ্ট নেভিগেশন আইটেম (প্যারেন্ট বা চাইল্ড) খুঁজে বের করা
  static NavigationItem? findItemByRoute(String route) {
    for (final module in mainModules) {
      if (module.route == route) return module;
      for (final child in module.children) {
        if (child.route == route) return child;
      }
    }
    return null;
  }

  /// ব্রেডক্রাম্ব পাথ তৈরি করা
  static List<BreadcrumbItem> getBreadcrumbs(String route) {
    if (route == RouteNames.dashboard || route == RouteNames.initial || route == RouteNames.shell) {
      return [
        const BreadcrumbItem(title: 'ড্যাশবোর্ড', route: RouteNames.dashboard, isCurrent: true),
      ];
    }

    final parent = findParentModuleByRoute(route);
    if (parent == null) {
      return [
        const BreadcrumbItem(title: 'ড্যাশবোর্ড', route: RouteNames.dashboard),
        BreadcrumbItem(title: route, route: route, isCurrent: true),
      ];
    }

    if (parent.route == route) {
      return [
        const BreadcrumbItem(title: 'ড্যাশবোর্ড', route: RouteNames.dashboard),
        BreadcrumbItem(title: parent.title, route: parent.route, isCurrent: true),
      ];
    }

    final child = parent.children.firstWhere(
      (c) => c.route == route,
      orElse: () => NavigationItem(
        id: 'unknown',
        title: route,
        icon: Icons.chevron_right,
        route: route,
        sortOrder: 99,
      ),
    );

    return [
      const BreadcrumbItem(title: 'ড্যাশবোর্ড', route: RouteNames.dashboard),
      BreadcrumbItem(title: parent.title, route: parent.route),
      BreadcrumbItem(title: child.title, route: child.route, isCurrent: true),
    ];
  }
